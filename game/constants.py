"""Константы и типы игры «Гномья крепость».

Правила описаны в README.md репозитория:
  - 4 игрока строят крепость за 20 ходов;
  - нужно добыть 25 камней (вытолкнуть за пределы поля);
  - камни появляются на жёлтых клетках;
  - за ход игрок делает 3 действия (шаг или экипировка);
  - камень / коробка / лазер можно толкнуть;
  - кристалл и гриб — непроходимы;
  - лазеры: зелёный (проход сквозь стены), красный (ломает грибы/кристаллы),
    жёлтый (ломает камни и убивает игроков);
  - драгоценные камни меняются на 3 обычных или 1 экипировку;
  - после 12 хода на зелёных клетках появляются гоблины-лазутчики,
    убивающие игрока на соседней (по стороне) клетке.
"""

from __future__ import annotations

from enum import IntEnum

# ---------------------------------------------------------------------------


class Tile(IntEnum):
    """Тип клетки поля."""

    EMPTY = 0        # пустая клетка
    WALL = 1         # стена
    ROCK = 2         # обычный строительный камень
    GEM = 3          # драгоценный камень
    BOX = 4          # коробка (толкается, как в sokoban)
    CRYSTAL = 5      # кристалл (непроходим, ломается красным лазером)
    MUSHROOM = 6     # гриб (непроходим, ломается красным лазером)
    LASER_R = 7      # красный лазер
    LASER_G = 8      # зелёный лазер
    LASER_Y = 9      # жёлтый лазер
    SPAWN_YELLOW = 10  # жёлтая клетка — на ней появляются камни
    SPAWN_GREEN = 11   # зелёная клетка — на ней появляются гоблины


